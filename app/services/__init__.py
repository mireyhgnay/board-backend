"""
📌 services/__init__.py - 비즈니스 로직 레이어

【 서비스 레이어란? 】
    비즈니스 로직(Business Logic)을 담당하는 레이어입니다.

    비즈니스 로직 = 앱의 핵심 규칙과 처리 과정
    예:
    - 게시글 작성 시 금지어 필터링
    - 회원 가입 시 이메일 중복 체크 + 비밀번호 해싱
    - 포인트 적립 로직
    - 알림 발송 처리

【 왜 서비스 레이어를 분리하나요? 】
    ┌────────────────────────────────────────────────────────────┐
    │  Router(API) → Service(비즈니스 로직) → Repository(DB 접근)  │
    └────────────────────────────────────────────────────────────┘

    Router: HTTP 요청/응답만 담당
    Service: 비즈니스 규칙 처리
    Repository: DB 쿼리만 담당

    관심사의 분리(Separation of Concerns) 원칙:
    각 레이어가 자신의 역할만 담당하면 코드가 깔끔하고 유지보수가 쉬워집니다.
    예를 들어 DB를 MySQL → PostgreSQL로 바꿔도 Repository만 수정하면 됩니다.

【 파일 추가 예시 】
    services/
    ├── user_service.py   # 유저 관련 비즈니스 로직
    ├── post_service.py   # 게시글 관련 비즈니스 로직
    └── auth_service.py   # 인증 관련 비즈니스 로직
"""
